# ── 辅助函数 ──────────────────────────────────────────────────

def is_noise(text: str) -> bool:
    """判断一段评语是否为无效内容（噪声）。"""
    t = text.strip().replace("\u3000", "").replace("\xa0", "")  # 全角空格 + nbsp
    if not t:
        return True
    if t in NOISE_EXACT:
        return True
    for pattern in NOISE_REGEX:
        if pattern.match(t):
            return True
    return False


def get_all_triggers() -> list[str]:
    """返回词典中所有触发词（用于外部分词/匹配时统一加载）。"""
    triggers: list[str] = []
    for axial, sub_dict in KEYWORD_DICT.items():
        for _, keywords in sub_dict.items():
            triggers.extend(keywords)
    # 去重并按长度降序排列（长词优先匹配）
    triggers = sorted(set(triggers), key=lambda x: (-len(x), x))
    return triggers


def resolve_axial(sub_code: str) -> str | None:
    """根据开放编码名称反查所属的主轴编码视角。"""
    for axial, sub_dict in KEYWORD_DICT.items():
        for sc_name, _keywords in sub_dict.items():
            if sc_name == sub_code:
                return axial
    return None


def resolve_axial_by_trigger(trigger: str) -> tuple[str, str] | None:
    """根据触发词反查 (主轴编码, 开放编码)。"""
    for axial, sub_dict in KEYWORD_DICT.items():
        for sc_name, keywords in sub_dict.items():
            if trigger in keywords:
                return axial, sc_name
    return None


